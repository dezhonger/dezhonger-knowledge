import { readFile, writeFile } from 'node:fs/promises'
import { webcrypto } from 'node:crypto'
import path from 'node:path'
import process from 'node:process'

const inputPath = readOption('--input')
const outputPath = readOption('--output')
const password = process.env.PUZZLE_SOLUTION_PASSWORD

if (!inputPath || !outputPath || !password) {
  throw new Error('Usage: PUZZLE_SOLUTION_PASSWORD=... node scripts/encrypt-puzzle-answers.mjs --input answers.json --output encrypted.ts')
}

function readOption(name) {
  const index = process.argv.indexOf(name)
  return index >= 0 ? process.argv[index + 1] : undefined
}

function toBase64(bytes) {
  return Buffer.from(bytes).toString('base64')
}

const { subtle } = webcrypto
const encoder = new TextEncoder()
const source = JSON.parse(await readFile(path.resolve(inputPath), 'utf8'))
const encrypted = {}

for (const [problem, translations] of Object.entries(source)) {
  encrypted[problem] = {}

  for (const [locale, html] of Object.entries(translations)) {
    const salt = webcrypto.getRandomValues(new Uint8Array(16))
    const iv = webcrypto.getRandomValues(new Uint8Array(12))
    const passwordKey = await subtle.importKey('raw', encoder.encode(password), 'PBKDF2', false, ['deriveKey'])
    const key = await subtle.deriveKey(
      { name: 'PBKDF2', hash: 'SHA-256', salt, iterations: 210_000 },
      passwordKey,
      { name: 'AES-GCM', length: 256 },
      false,
      ['encrypt'],
    )
    const additionalData = encoder.encode(`project-euler:${problem}:${locale}`)
    const ciphertext = await subtle.encrypt({ name: 'AES-GCM', iv, additionalData }, key, encoder.encode(html))

    encrypted[problem][locale] = {
      iterations: 210_000,
      salt: toBase64(salt),
      iv: toBase64(iv),
      ciphertext: toBase64(new Uint8Array(ciphertext)),
    }
  }
}

const generated = `// Generated by scripts/encrypt-puzzle-answers.mjs. Plaintext answers are intentionally not committed.\n\nexport interface EncryptedPuzzleAnswer {\n  iterations: number\n  salt: string\n  iv: string\n  ciphertext: string\n}\n\nexport const encryptedProjectEulerAnswers: Record<string, Record<'en' | 'zh', EncryptedPuzzleAnswer>> = ${JSON.stringify(encrypted, null, 2)}\n`

await writeFile(path.resolve(outputPath), generated)
console.log(`Encrypted ${Object.keys(source).length} puzzle answers into ${outputPath}`)
